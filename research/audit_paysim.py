"""Read PaySim ZIP in chunks; never extract or publish account identifiers."""
import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path
from zipfile import ZipFile
import pandas as pd

def audit(path):
    digest=hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda:f.read(1024*1024),b''):digest.update(chunk)
    totals=Counter();fraud_types=Counter();first_fraud={};fraud_senders={}
    with ZipFile(path) as z:
        members=[item for item in z.infolist() if item.filename.lower().endswith('.csv') and not item.filename.startswith('__MACOSX/')]
        if len(members)!=1 or members[0].file_size>1_000_000_000:raise ValueError('Ожидается один CSV разумного размера в архиве.')
        with z.open(members[0]) as src:
            for chunk in pd.read_csv(src,usecols=['step','type','nameOrig','nameDest','isFraud'],chunksize=250_000):
                totals['transactions']+=len(chunk)
                fraud=chunk[chunk.isFraud==1];totals['fraud_transactions']+=len(fraud)
                fraud_types.update(fraud['type'].value_counts().to_dict())
                for row in fraud[fraud.type=='TRANSFER'].itertuples(index=False):
                    receiver=str(row.nameDest);first_fraud[receiver]=min(first_fraud.get(receiver,int(row.step)),int(row.step))
                    fraud_senders.setdefault(receiver,set()).add(str(row.nameOrig))
        history={receiver:0 for receiver in first_fraud};prior_senders={receiver:set() for receiver in first_fraud}
        same_step={receiver:0 for receiver in first_fraud}
        with z.open(members[0]) as src:
            for chunk in pd.read_csv(src,usecols=['step','nameOrig','nameDest'],chunksize=250_000):
                selected=chunk[chunk.nameDest.isin(first_fraud)]
                for row in selected.itertuples(index=False):
                    receiver=str(row.nameDest);step=int(row.step)
                    if step<first_fraud[receiver]:history[receiver]+=1;prior_senders[receiver].add(str(row.nameOrig))
                    elif step==first_fraud[receiver]:same_step[receiver]+=1
    return {'source':'PaySim, synthetic; copy LordNR/AMLGraphX-Paysim','archive_sha256':digest.hexdigest(),**totals,
        'fraud_types':dict(fraud_types),'fraud_transfer_recipients':len(first_fraud),
        'fraud_transfer_recipients_with_prior_incoming':sum(x>0 for x in history.values()),
        'fraud_transfer_recipients_with_prior_multiple_senders':sum(len(x)>=2 for x in prior_senders.values()),
        'fraud_transfer_recipients_multiple_fraud_senders_all_time':sum(len(x)>=2 for x in fraud_senders.values()),
        'fraud_transfer_recipients_multiple_incoming_same_first_step':sum(x>=2 for x in same_step.values()),
        'limitations':['step is an hour; transactions within the same step have no verified order and are excluded from prior history.',
        'isFraud labels transactions generated by the simulator, not real-world victim-to-scammer transfers.',
        'Retrospective counts are not model results; they do not validate the utility of recipient history for a given transaction.']}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('archive',type=Path);parser.add_argument('--output',type=Path);args=parser.parse_args()
    result=audit(args.archive);text=json.dumps(result,ensure_ascii=False,indent=2)
    if args.output:args.output.write_text(text,encoding='utf-8')
    print(text)
